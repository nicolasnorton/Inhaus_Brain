class BlueprintTemplate {
  final String id;
  final String title;
  final String industry;
  final String challenge;
  final String techStack;
  final String blueprintFlow;

  const BlueprintTemplate({
    required this.id,
    required this.title,
    required this.industry,
    required this.challenge,
    required this.techStack,
    required this.blueprintFlow,
  });

  AppTemplate toAppTemplate() {
    return AppTemplate(
      id: 'bp_${id}',
      name: title,
      description: '$industry: $challenge',
      icon: _getIconForIndustry(industry),
      appType: AppType.workflow,
      defaultConfig: {},
      pipelineSteps: [
        PipelineStep(
          id: 'start',
          nodeType: WorkflowNodeType.trigger,
          instruction: 'Start Blueprint',
          uiPosition: {'x': 100, 'y': 300},
        ),
        PipelineStep(
          id: 'plan_architecture',
          nodeType: WorkflowNodeType.llm,
          instruction: 'Generate Architecture Spec',
          uiPosition: {'x': 400, 'y': 300},
          dependencies: ['start'],
          config: {
            'model': 'gemini-3-pro-preview',
            'prompt': '''
You are a Cloud Solution Architect. Generate a detailed technical architecture specification for the following use case.

**Use Case**: $title
**Industry**: $industry
**Challenge**: $challenge
**Recommended Tech Stack**: $techStack
**Blueprint Pattern**: $blueprintFlow

**Output Format**:
1. **Executive Summary**: 1-2 sentences.
2. **Architecture Diagram** (Mermaid.js format).
3. **Component Breakdown**: Explain role of each tech stack component.
4. **Implementation Guide**: Step-by-step implementation plan.
'''
          },
        ),
        PipelineStep(
          id: 'output_plan',
          nodeType: WorkflowNodeType.answer,
          instruction: 'View Architecture',
          uiPosition: {'x': 800, 'y': 300},
          dependencies: ['plan_architecture'],
          config: {
            'text': '{{plan_architecture.output}}'
          },
        ),
      ],
    );
  }

  String _getIconForIndustry(String industry) {
    switch (industry.toLowerCase()) {
      case 'retail': return '🛍️';
      case 'consumer packaged goods': return '🥫';
      case 'media & entertainment': return '🎬';
      case 'automotive & logistics': return '🚛';
      case 'financial services': return '💸';
      case 'healthcare & life sciences': return '🏥';
      case 'manufacturing & energy': return '🏭';
      case 'travel & hospitality': return '✈️';
      case 'public sector & impact': return '🏛️';
      case 'productivity & cross-industry': return '🚀';
      default: return '📐';
    }
  }
}

